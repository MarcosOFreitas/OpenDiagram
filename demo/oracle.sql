-- runs as SYS; switch to the PDB, objects go to app user SHOP
alter session set container = FREEPDB1;
grant create materialized view, create view, create sequence, create trigger to shop;
alter session set current_schema = shop;
create table customers (
  id number(10) primary key,
  email varchar2(255) not null,
  name varchar2(100),
  created_at date default sysdate
);
create unique index uq_customers_email on customers (email);
comment on table customers is 'Registered customers';
comment on column customers.email is 'Login email';
create table orders (
  id number(10) primary key,
  customer_id number(10) not null,
  status varchar2(20) default 'new',
  constraint fk_orders_customer foreign key (customer_id) references customers(id) on delete cascade
);
create index idx_orders_status on orders (status);
create table order_items (
  order_id number(10) not null,
  line_no number(5) not null,
  qty number(5) default 1 not null,
  constraint pk_order_items primary key (order_id, line_no),
  constraint fk_items_order foreign key (order_id) references orders(id)
);

-- A1 objects: view, materialized view (also appears as a TABLE of the same name), sequence, trigger
create view v_customer_orders as select c.id customer_id, c.name, o.id order_id, o.status from customers c join orders o on o.customer_id = c.id;
-- a materialized view must be created by its owner
connect shop/shop@//localhost/FREEPDB1
create materialized view mv_orders_by_status as select status, count(*) total from orders group by status;
-- invoice_seq is used by nothing: it stays a loose Note
create sequence invoice_seq start with 1000 increment by 1;
-- ticket_seq is used by a trigger: it goes into the note of the table of that trigger
create sequence ticket_seq start with 1 increment by 1;
create table tickets (id number(10) primary key, subject varchar2(100));
create or replace trigger trg_tickets_bi before insert on tickets for each row begin :new.id := ticket_seq.nextval; end;
/
create or replace trigger trg_orders_bi before insert on orders for each row begin null; end;
/

-- check constraints and partitioning: a named check, a NOT NULL (a system check, left out), a disabled check (left out) and a partitioned table
alter table order_items add constraint ck_items_qty check (qty > 0);
create table events (
  id number(10) not null,
  kind varchar2(10) not null,
  created_at date not null,
  constraint ck_events_kind check (kind in ('click', 'view')),
  constraint ck_events_soft check (id < 100) disable
) partition by range (created_at) (partition p2026 values less than (to_date('2027-01-01', 'YYYY-MM-DD')), partition pmax values less than (maxvalue));

-- identity (increment) and a virtual column (its expression in the note); @dbml/core's Oracle importer cannot read the virtual column
create table invoices (
  id number(10) generated by default as identity primary key,
  net number(10,2) not null,
  vat number(10,2) not null,
  gross number(10,2) generated always as (net + vat) virtual
);
